    const langDict = TRANSLATIONS[currentLangCode] || TRANSLATIONS['en'];
    if (langDict && langDict[key] !== undefined) {
      return langDict[key];
    }
    // Fallback to English
    return TRANSLATIONS['en'][key] || key;
